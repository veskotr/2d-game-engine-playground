local function near(a, b) assert(math.abs(a - b) < 0.0001) end
function runGameplayControls(parent)
    local children = Engine.getChildren(parent)
    assert(#children == 1)
    local child = children[1]
    assert(Engine.setTransformPosition(parent, 10, 20))
    assert(Engine.setTransformScale(parent, 2, 3))
    assert(Engine.setTransformRotation(parent, math.pi / 2))
    assert(Engine.setTransformPosition(child, 4, 5))
    assert(Engine.setTransformScale(child, 0.5, 2))
    assert(Engine.setTransformRotation(child, 0.25))
    near(Engine.getTransformRotation(child), 0.25)
    local world = Engine.getWorldTransform(child)
    near(world.position.x, -5); near(world.position.y, 28)
    near(world.scale.x, 1); near(world.scale.y, 6)
    near(world.rotation, math.pi / 2 + 0.25)
    Engine.setTransformPosition(parent, 20, 30)
    world = Engine.getWorldTransform(child)
    near(world.position.x, 5); near(world.position.y, 38)
    near(Engine.Physics.getGravityScale(child), 0.375)
    assert(Engine.Physics.getGravityScale(parent) == nil)
    local delta = Engine.Input.getMouseDelta()
    near(delta.x, 0); near(delta.y, 0)
    for _, button in ipairs({0, 1, 2, -1, 999}) do
        assert(Engine.Input.isMouseButtonDown(button) == false)
        assert(Engine.Input.isMouseButtonPressed(button) == false)
        assert(Engine.Input.isMouseButtonReleased(button) == false)
    end
    assert(type(Engine.Input.getMousePosition) == "function")
    assert(type(Engine.Physics.setGravityScale) == "function")
    for _, bad in ipairs({-1, 4294967296, 1.5, "1", false}) do
        assert(not pcall(Engine.getTransformRotation, bad))
        assert(not pcall(Engine.getChildren, bad))
    end
    assert(Engine.getTransformRotation(0) == nil)
    assert(#Engine.getChildren(0) == 0)
    assert(Engine.setTransformRotation(0, 1) == false)
    assert(not pcall(Engine.setTransformScale, child, math.huge, 1))
    assert(not pcall(Engine.setTransformRotation, child, 0/0))
    Engine.destroyEntity(child)
    assert(#children == 1)
    assert(#Engine.getChildren(parent) == 0)
    assert(Engine.getWorldTransform(child) == nil)
    assert(Engine.getTransformRotation(child) == nil)
    assert(Engine.setTransformRotation(child, 1) == false)
end
