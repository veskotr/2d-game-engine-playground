fun editorColors(mode: EditorThemeMode): EditorColors = if(mode==EditorThemeMode.Dark) dark else light
val LocalEditorColors=staticCompositionLocalOf { dark }
val LocalEditorAppearance=staticCompositionLocalOf { EditorAppearance() }

fun EditorColors.material(mode: EditorThemeMode): Colors {
    val base=if(mode==EditorThemeMode.Dark) darkColors() else lightColors()
    return base.copy(primary=accent,primaryVariant=accent,secondary=accent,secondaryVariant=accent,
        background=background,surface=surface,error=error,onPrimary=accentOnPrimary,
        onSecondary=accentOnPrimary,onBackground=textPrimary,onSurface=textPrimary,onError=background)
}
