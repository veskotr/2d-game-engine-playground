function check_scene_keys()
    local child = assert(Engine.findEntityByKey('child'))
    local rig = assert(Engine.findEntityByKey('rig'))
    local leaf = assert(Engine.findEntityByKey('leaf'))
    assert(Engine.getParent(child) == rig)
    assert(Engine.Components.get(child, 'Animator').targetEntities.leaf == leaf)
    assert(Engine.findEntityByKey('missing') == nil)
    assert(Engine.findEntityByKey('display only') == nil)
    assert(Engine.findEntityByKey('RIG') == nil)
    assert(Engine.findEntityByKey('') == nil)
    assert(Engine.findEntityByKey('rig\0suffix') == nil)
    assert(not pcall(Engine.findEntityByKey, {}))
end
function remove_scene_keys()
    local rig = assert(Engine.findEntityByKey('rig'))
    Engine.destroyEntity(rig)
    assert(Engine.findEntityByKey('rig') == nil)
    assert(Engine.findEntityByKey('child') == nil)
    assert(Engine.findEntityByKey('holder') == nil)
    assert(Engine.findEntityByKey('leaf') == nil)
end
